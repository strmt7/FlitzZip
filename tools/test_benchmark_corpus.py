"""Offline admission tests; fixtures are generated and are never performance evidence."""

from __future__ import annotations

import hashlib
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from tools import benchmark_corpus as corpus
from tools import run_archive_comparison as comparison


class CorpusAdmissionTests(unittest.TestCase):
    # Purpose: Bound metadata reads independently of manifest validation and reject empty or oversized bytes.
    # Inputs: Owned temporary metadata with exact boundary and excess-byte fixtures.
    # Outputs: One-MiB metadata hashes exactly; empty and excess payloads fail before admission.
    def test_metadata_read_ceiling(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "metadata.json"
            for payload in (b"", b"x" * (1024 * 1024 + 1)):
                path.write_bytes(payload)
                with self.assertRaisesRegex(ValueError, "metadata must contain"):
                    corpus.metadata_digest(path)
            payload = b"x" * (1024 * 1024)
            path.write_bytes(payload)
            self.assertEqual(corpus.metadata_digest(path), hashlib.sha256(payload).hexdigest())

    # Purpose: Verify shared permission admission, exact natural extent and frozen metadata without timing code.
    # Inputs: Owned generated bytes, a mocked permission decision and private manifest/catalog fixtures.
    # Outputs: Exact public provenance passes; absent selection, wrong bytes, denied rights and mutations fail.
    def test_shared_admission_and_mutations(self) -> None:
        payload = b"owned offline correctness fixture\n" * 5 + b"tail"
        source = "https://example.invalid/owned-fixture"
        entry = {
            "name": "sample.csv",
            "bytes": len(payload),
            "sha256": hashlib.sha256(payload).hexdigest(),
            "subject": "owned-fixture",
            "source_url": source,
            "transformation": "generated test fixture; not benchmark data",
        }
        spec = {
            "schema_version": 1,
            "name": "offline generated fixture",
            "files": [entry],
            "cases": [{"name": "csv", "format": "zst", "files": [entry["name"]], "tools": ["SuperZip", "Zstd"]}],
        }
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            raw = root / entry["name"]
            raw.write_bytes(payload)
            manifest, catalog = root / "manifest.json", root / "catalog.json"
            manifest.write_text(json.dumps(spec), encoding="utf-8")
            catalog.write_text("owned fixture catalog", encoding="utf-8")
            with (
                patch.object(corpus, "PERMISSIONS_PATH", catalog),
                patch.object(comparison, "require_permission", return_value={"evidence": [source]}) as permission,
            ):
                record = corpus.inspect_corpus(manifest, root, entry["name"])
                permission.assert_called_once_with("owned-fixture", "execute")
                self.assertEqual(record["input_bytes"], len(payload))
                self.assertEqual(record["source_sha256"], entry["sha256"])
                self.assertEqual(record["provenance"]["file"], entry)
                self.assertNotIn(str(root), json.dumps(record["provenance"]))
                for target in (manifest, catalog):
                    original = target.read_bytes()
                    verify = corpus.verify_manifest

                    # Purpose: Change metadata only after the canonical verifier has authenticated its inputs.
                    # Inputs: Arguments are forwarded to the real manifest verifier; target is an owned fixture.
                    # Outputs: Original result with a concurrent mutation, allowing the outer freeze check to reject it.
                    def mutate(*args, verify=verify, target=target, original=original):
                        result = verify(*args)
                        target.write_bytes(original + b"\n")
                        return result

                    with (
                        patch.object(corpus, "verify_manifest", side_effect=mutate),
                        self.assertRaisesRegex(ValueError, "changed during admission"),
                    ):
                        corpus.inspect_corpus(manifest, root, entry["name"])
                    target.write_bytes(original)
                with self.assertRaisesRegex(ValueError, "absent"):
                    corpus.inspect_corpus(manifest, root, "absent.csv")
                raw.write_bytes(b"x" * len(payload))
                with self.assertRaisesRegex(ValueError, "SHA-256 differs"):
                    corpus.inspect_corpus(manifest, root, entry["name"])
                raw.write_bytes(payload)
                with (
                    patch.object(comparison, "require_permission", side_effect=ValueError("rights denied")),
                    self.assertRaisesRegex(ValueError, "rights denied"),
                ):
                    corpus.inspect_corpus(manifest, root, entry["name"])


if __name__ == "__main__":
    unittest.main()
